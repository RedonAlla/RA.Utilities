    private static void AppendResponseSend(StringBuilder builder, MessageModel message, string handlerFullyQualifiedName)
    {
        string messageType = message.MessageFullyQualifiedName;
        string responseType = message.ResponseFullyQualifiedName!;
        string handlerServiceType = handlerFullyQualifiedName.Length > 0
            ? handlerFullyQualifiedName
            : $"global::RA.Utilities.Feature.Abstractions.IRequestHandler<{messageType}, {responseType}>";

        AppendLine(builder, 2, $"public global::System.Threading.Tasks.Task<{responseType}> Send({messageType} request, global::System.Threading.CancellationToken cancellationToken = default)");
        AppendLine(builder, 2, "{");
        AppendRequestSendBody(builder, messageType, responseType, RequestNullCheck(message), handlerServiceType, useInterfaceBehaviorCast: false);
        AppendLine(builder, 2, "}");
    }

