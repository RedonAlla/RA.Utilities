    /// <summary>
    /// Emits the behavior service enumeration. Closed monomorphic bodies use the direct array
    /// cast; the generic interface bodies use the variance-free <see cref="Array"/> cast so that
    /// JIT generic sharing cannot break the cast.
    /// </summary>
    private static void AppendBehaviorEnumeration(
        StringBuilder builder,
        int depth,
        string messageType,
        string? responseType,
        bool hasResponse,
        bool useInterfaceBehaviorCast)
    {
        string behaviorInterface = hasResponse
            ? $"global::RA.Utilities.Feature.Abstractions.IPipelineBehavior<{messageType}, {responseType}>"
            : $"global::RA.Utilities.Feature.Abstractions.IPipelineBehavior<{messageType}>";

        AppendLine(builder, depth, $"global::System.Collections.Generic.IEnumerable<{behaviorInterface}> behaviorServices =");
        AppendLine(builder, depth + 1, $"global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetServices<{behaviorInterface}>(_provider);");

        if (useInterfaceBehaviorCast)
        {
            AppendLine(builder, depth, "global::System.Array behaviors = behaviorServices as global::System.Array ?? global::System.Linq.Enumerable.ToArray(behaviorServices);");
        }
        else
        {
            AppendLine(builder, depth, $"{behaviorInterface}[] behaviors = behaviorServices as {behaviorInterface}[] ?? global::System.Linq.Enumerable.ToArray(behaviorServices);");
        }
    }

    /// <summary>
    /// Emits the reversed delegate chain so the first registered behavior is outermost. Each step
    /// snapshots the current chain into a fresh local that is never reassigned — capturing the
    /// reassigned <c>next</c> variable itself would make every wrapper call itself recursively.
    /// </summary>
    private static void AppendBehaviorChain(
        StringBuilder builder,
        int depth,
        string messageType,
        string? responseType,
        bool hasResponse,
        bool hasContext,
        bool useInterfaceBehaviorCast)
    {
        string behaviorInterface = hasResponse
            ? $"global::RA.Utilities.Feature.Abstractions.IPipelineBehavior<{messageType}, {responseType}>"
            : $"global::RA.Utilities.Feature.Abstractions.IPipelineBehavior<{messageType}>";
        string delegateType;
        if (hasResponse)
        {
            delegateType = hasContext
                ? $"global::RA.Utilities.Feature.Models.RequestHandlerContextDelegate<{responseType}, TContext>"
                : $"global::RA.Utilities.Feature.Models.RequestHandlerDelegate<{responseType}>";
        }
        else
        {
            delegateType = hasContext
                ? "global::RA.Utilities.Feature.Models.RequestHandlerContextDelegate<TContext>"
                : "global::RA.Utilities.Feature.Models.RequestHandlerDelegate";
        }
        string elementRead = useInterfaceBehaviorCast
            ? $"({behaviorInterface})behaviors.GetValue(i)!"
            : "behaviors[i]";

        AppendLine(builder, depth, "for (int i = behaviors.Length - 1; i >= 0; i--)");
        AppendLine(builder, depth, "{");
        AppendLine(builder, depth + 1, $"{behaviorInterface} behavior = {elementRead};");
        AppendLine(builder, depth + 1, $"{delegateType} previous = next;");
        AppendLine(builder, depth + 1, hasContext
            ? "next = c => behavior.HandleAsync<TContext>(request, previous, c, cancellationToken);"
            : "next = () => behavior.HandleAsync(request, previous, cancellationToken);");
        AppendLine(builder, depth, "}");
    }

    /// <summary>
    /// Emits the notification fan-out body mirroring the historical publish semantics
    /// (per-handler behavior wrapping and logged-and-swallowed handler failures).
    /// </summary>
    private static void AppendPublishBody(StringBuilder builder, string notificationType, bool hasContext)
    {
        AppendLine(builder, 3, $"global::System.Collections.Generic.List<global::RA.Utilities.Feature.Abstractions.INotificationHandler<{notificationType}>> handlers =");
        AppendLine(builder, 4, $"global::System.Linq.Enumerable.ToList(global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetServices<global::RA.Utilities.Feature.Abstractions.INotificationHandler<{notificationType}>>(_provider));");
        AppendLine(builder, 3, "if (handlers.Count == 0) { return; }");
        AppendLine(builder, 3, $"global::System.Collections.Generic.List<global::RA.Utilities.Feature.Abstractions.INotificationBehavior<{notificationType}>> behaviors =");
        AppendLine(builder, 4, $"global::System.Linq.Enumerable.ToList(global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetServices<global::RA.Utilities.Feature.Abstractions.INotificationBehavior<{notificationType}>>(_provider));");
        AppendLine(builder, 3, $"foreach (global::RA.Utilities.Feature.Abstractions.INotificationHandler<{notificationType}> handler in handlers)");
        AppendLine(builder, 3, "{");
        AppendLine(builder, 4, "try");
        AppendLine(builder, 4, "{");

        if (hasContext)
        {
            AppendLine(builder, 5, "global::RA.Utilities.Feature.Models.NotificationHandlerContextDelegate<TContext> handlerDelegate = c => handler.HandleAsync<TContext>(notification, c, cancellationToken);");
        }
        else
        {
            AppendLine(builder, 5, "global::RA.Utilities.Feature.Models.NotificationHandlerDelegate handlerDelegate = () => handler.HandleAsync(notification, cancellationToken);");
        }

        AppendLine(builder, 5, "for (int i = behaviors.Count - 1; i >= 0; i--)");
        AppendLine(builder, 5, "{");
        AppendLine(builder, 6, $"global::RA.Utilities.Feature.Abstractions.INotificationBehavior<{notificationType}> behavior = behaviors[i];");
        AppendLine(builder, 6, hasContext
            ? "global::RA.Utilities.Feature.Models.NotificationHandlerContextDelegate<TContext> previous = handlerDelegate;"
            : "global::RA.Utilities.Feature.Models.NotificationHandlerDelegate previous = handlerDelegate;");
        AppendLine(builder, 6, hasContext
            ? "handlerDelegate = c => behavior.HandleAsync<TContext>(notification, previous, c, cancellationToken);"
            : "handlerDelegate = () => behavior.HandleAsync(notification, previous, cancellationToken);");
        AppendLine(builder, 5, "}");

        if (hasContext)
        {
            AppendLine(builder, 5, "if (behaviors.Count == 0) { await handler.HandleAsync<TContext>(notification, ctx, cancellationToken); }");
            AppendLine(builder, 5, "else { await handlerDelegate(ctx); }");
        }
        else
        {
            AppendLine(builder, 5, "if (behaviors.Count == 0) { await handler.HandleAsync(notification, cancellationToken); }");
            AppendLine(builder, 5, "else { await handlerDelegate(); }");
        }

        AppendLine(builder, 4, "}");
        AppendLine(builder, 4, "catch (global::System.Exception ex)");
        AppendLine(builder, 4, "{");
        AppendLine(builder, 5, $"global::Microsoft.Extensions.Logging.LoggerExtensions.LogError(_logger, ex, \"[Publish] Handler {{HandlerType}} failed for notification {{NotificationType}}. Notification: {{@Notification}}\", handler.GetType().Name, typeof({notificationType}).Name, notification);");
        AppendLine(builder, 4, "}");
        AppendLine(builder, 3, "}");
    }

