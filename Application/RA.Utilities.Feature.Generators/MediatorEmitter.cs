    private static void AppendRequestSendBody(
        StringBuilder builder,
        string messageType,
        string responseType,
        string nullCheckLine,
        string handlerServiceType,
        bool useInterfaceBehaviorCast)
    {
        if (nullCheckLine.Length > 0)
        {
            AppendLine(builder, 3, nullCheckLine);
        }

        AppendLine(builder, 3, $"{handlerServiceType} handler =");
        AppendLine(builder, 4, $"global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{handlerServiceType}>(_provider);");

        AppendBehaviorEnumeration(builder, 3, messageType, responseType, hasResponse: true, useInterfaceBehaviorCast);
        AppendLine(builder, 3, "if (behaviors.Length == 0) { return handler.HandleAsync(request, cancellationToken); }");
        AppendLine(builder, 3, $"global::RA.Utilities.Feature.Models.RequestHandlerDelegate<{responseType}> next = () => handler.HandleAsync(request, cancellationToken);");
        AppendBehaviorChain(builder, 3, messageType, responseType, hasResponse: true, hasContext: false, useInterfaceBehaviorCast);
        AppendLine(builder, 3, "return next();");
    }

    private static void AppendRequestContextSendBody(
        StringBuilder builder,
        string messageType,
        string responseType,
        string nullCheckLine,
        string handlerServiceType,
        string handlerContextCall,
        bool useInterfaceBehaviorCast)
    {
        if (nullCheckLine.Length > 0)
        {
            AppendLine(builder, 3, nullCheckLine);
        }

        AppendLine(builder, 3, "global::RA.Utilities.Feature.Models.PipelineContext<TContext> ctx = context ?? new global::RA.Utilities.Feature.Models.PipelineContext<TContext>();");
        AppendLine(builder, 3, $"{handlerServiceType} handler =");
        AppendLine(builder, 4, $"global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{handlerServiceType}>(_provider);");

        AppendBehaviorEnumeration(builder, 3, messageType, responseType, hasResponse: true, useInterfaceBehaviorCast);
        AppendLine(builder, 3, $"if (behaviors.Length == 0) {{ return {handlerContextCall.Replace("request, c, cancellationToken", "request, ctx, cancellationToken")}; }}");
        AppendLine(builder, 3, $"global::RA.Utilities.Feature.Models.RequestHandlerContextDelegate<{responseType}, TContext> next = c => {handlerContextCall};");
        AppendBehaviorChain(builder, 3, messageType, responseType, hasResponse: true, hasContext: true, useInterfaceBehaviorCast);
        AppendLine(builder, 3, "return next(ctx);");
    }

