namespace RA.Utilities.Feature.Generators;

/// <summary>
/// Builds the generated <c>Mediator</c> class — the sole <c>IMediator</c> implementation —
/// with monomorphized per-message dispatch: the known handler is injected by concrete type and
/// called directly, behaviors resolve through DI (picking up both auto-registered and explicitly
/// registered pipeline behaviors), and the zero-behavior path calls the handler with no delegate
/// chain at all. The generic interface methods carry the same bodies, monomorphized by the JIT.
/// </summary>
internal static class MediatorEmitter
{
    /// <summary>
    /// The standard header for generated files. The <c>auto-generated</c> marker makes analyzers skip
    /// the file, and the pragma silences compiler warnings (such as CS1591) in consumer projects
    /// that build with warnings as errors.
    /// </summary>
    private const string GeneratedFileHeader = "// <auto-generated/>\n#pragma warning disable\n#nullable enable\n\n";

    /// <summary>
    /// The hint name of the generated source file.
    /// </summary>
    private const string HintName = "RA.Utilities.Feature.Mediator.g.cs";

    /// <summary>
    /// The project-size threshold above which the object-based dispatch switches from
    /// <c>typeof</c> if-chains to static dictionary lookups.
    /// </summary>
    public const int DictionaryThreshold = 8;

    /// <summary>
    /// Emits the generated mediator implementation, its registration initializer, and the
    /// message/handler diagnostics.
    /// </summary>
    /// <param name="context">The source production context.</param>
    /// <param name="sourceMessages">The message models discovered in the current compilation.</param>
    /// <param name="sourceHandlers">The handler and behavior models discovered in the current compilation.</param>
    /// <param name="referenced">The models discovered in referenced assemblies.</param>
    /// <param name="contractsPresent">Whether the compilation references the runtime contracts.</param>
    /// <param name="moduleInitializersSupported">Whether the target framework supports module initializers.</param>
    /// <param name="initializerDisabled">Whether the registration initializer emission is disabled by the test seam.</param>
    public static void Emit(
        SourceProductionContext context,
        EquatableArray<MessageModel> sourceMessages,
        EquatableArray<HandlerModel> sourceHandlers,
        ReferencedAssemblyModels referenced,
        bool contractsPresent,
        bool moduleInitializersSupported,
        bool initializerDisabled)
    {
        if (!contractsPresent)
        {
            return;
        }

        EquatableArray<MessageModel> allMessages = CombineMessages(sourceMessages, referenced.Messages);
        EquatableArray<HandlerModel> allHandlers = CombineHandlers(sourceHandlers, referenced.Handlers);

        ReportDiagnostics(context, sourceMessages, allMessages, allHandlers);

        EquatableArray<MessageModel> cleanMessages = allMessages.Where(static message => !message.IsDiagnostic).ToImmutableArray();
        if (cleanMessages.IsDefaultOrEmpty)
        {
            return;
        }

        if (!moduleInitializersSupported)
        {
            context.ReportDiagnostic(Diagnostic.Create(Diagnostics.ModuleInitializersUnavailable, Location.None));
            return;
        }

        context.AddSource(HintName, SourceText.From(BuildSource(cleanMessages, allHandlers, initializerDisabled), Encoding.UTF8));
    }

    /// <summary>
    /// Combines the source and referenced message models, deduplicates on value equality (so
    /// partial declarations collapse), and sorts by kind and name for deterministic emission.
    /// </summary>
    private static EquatableArray<MessageModel> CombineMessages(
        EquatableArray<MessageModel> sourceMessages,
        EquatableArray<MessageModel> referencedMessages) =>
        sourceMessages
            .Concat(referencedMessages)
            .Distinct()
            .OrderBy(static message => message.Kind)
            .ThenBy(static message => message.MessageFullyQualifiedName, StringComparer.Ordinal)
            .ToImmutableArray();

    private static EquatableArray<HandlerModel> CombineHandlers(
        EquatableArray<HandlerModel> sourceHandlers,
        EquatableArray<HandlerModel> referencedHandlers) =>
        sourceHandlers
            .Concat(referencedHandlers)
            .Distinct()
            .OrderBy(static handler => handler.Kind)
            .ThenBy(static handler => handler.HandlerFullyQualifiedName, StringComparer.Ordinal)
            .ToImmutableArray();

    /// <summary>
    /// Reports the message contract diagnostics (FEAG006, FEAG008), the missing-handler warnings
    /// (FEAG007), and the dual-contract handler warnings (FEAG009).
    /// </summary>
    private static void ReportDiagnostics(
        SourceProductionContext context,
        EquatableArray<MessageModel> sourceMessages,
        EquatableArray<MessageModel> allMessages,
        EquatableArray<HandlerModel> allHandlers)
    {
        var reported = new HashSet<string>(StringComparer.Ordinal);

        foreach (MessageModel message in sourceMessages)
        {
            if (message.Diagnostic is not DiagnosticModel diagnostic)
            {
                continue;
            }

            string key = diagnostic.Descriptor.Id + "|" + message.TypeName;
            if (!reported.Add(key))
            {
                continue;
            }

            context.ReportDiagnostic(Diagnostic.Create(
                diagnostic.Descriptor,
                diagnostic.Location,
                diagnostic.Arguments));
        }

        // FEAG007: in-source request messages without a handler anywhere in the compilation.
        var handledRequests = new HashSet<string>(StringComparer.Ordinal);
        foreach (HandlerModel handler in allHandlers)
        {
            if (!handler.IsDiagnostic && handler.Kind is HandlerKind.VoidRequest or HandlerKind.RequestResponse)
            {
                handledRequests.Add(handler.RequestFullyQualifiedName);
            }
        }

        foreach (MessageModel message in allMessages)
        {
            if (message.IsDiagnostic
                || message.Kind == MessageKind.Notification
                || message.Location == Location.None
                || handledRequests.Contains(message.MessageFullyQualifiedName))
            {
                continue;
            }

            string key = Diagnostics.RequestMessageHasNoHandler.Id + "|" + message.TypeName;
            if (!reported.Add(key))
            {
                continue;
            }

            context.ReportDiagnostic(Diagnostic.Create(
                Diagnostics.RequestMessageHasNoHandler,
                message.Location,
                message.TypeName));
        }

        // FEAG009: a handler class implementing both the void and the request/response contract
        // for the same message.
        var reportedHandlers = new HashSet<string>(StringComparer.Ordinal);
        foreach (IGrouping<(string Handler, string Request), HandlerModel> group in allHandlers
            .Where(static handler => !handler.IsDiagnostic
                && handler.Kind is HandlerKind.VoidRequest or HandlerKind.RequestResponse)
            .GroupBy(static handler => (handler.HandlerFullyQualifiedName, handler.RequestFullyQualifiedName)))
        {
            bool hasVoid = group.Any(static handler => handler.Kind == HandlerKind.VoidRequest);
            bool hasResponse = group.Any(static handler => handler.Kind == HandlerKind.RequestResponse);
            if (!hasVoid || !hasResponse)
            {
                continue;
            }

            string key = Diagnostics.HandlerImplementsBothContracts.Id + "|" + group.Key.Handler + "|" + group.Key.Request;
            if (!reportedHandlers.Add(key))
            {
                continue;
            }

            HandlerModel anchor = group.FirstOrDefault(static handler => handler.Location != Location.None);
            if (anchor.Location is null)
            {
                anchor = group.First();
            }

            context.ReportDiagnostic(Diagnostic.Create(
                Diagnostics.HandlerImplementsBothContracts,
                anchor.Location,
                anchor.TypeName,
                StripGlobalPrefix(anchor.RequestFullyQualifiedName)));
        }
    }

    private static string StripGlobalPrefix(string fullyQualifiedName) =>
        fullyQualifiedName.StartsWith("global::", StringComparison.Ordinal)
            ? fullyQualifiedName.Substring("global::".Length)
            : fullyQualifiedName;

    /// <summary>
    /// Finds the concrete handler type for a message, or an empty string when the handler is
    /// generic or not discoverable (in which case the generated code resolves the handler
    /// interface instead).
    /// </summary>
    private static string GetHandlerFullyQualifiedName(EquatableArray<HandlerModel> allHandlers, MessageModel message)
    {
        foreach (HandlerModel handler in allHandlers)
        {
            if (!handler.IsDiagnostic
                && handler.Kind is HandlerKind.VoidRequest or HandlerKind.RequestResponse
                && string.Equals(handler.RequestFullyQualifiedName, message.MessageFullyQualifiedName, StringComparison.Ordinal))
            {
                return handler.HandlerFullyQualifiedName;
            }
        }

        return string.Empty;
    }

    private static string BuildSource(EquatableArray<MessageModel> messages, EquatableArray<HandlerModel> allHandlers, bool initializerDisabled)
    {
        EquatableArray<MessageModel> responseMessages = messages
            .Where(static message => message.Kind == MessageKind.RequestResponse)
            .ToImmutableArray();
        EquatableArray<MessageModel> voidMessages = messages
            .Where(static message => message.Kind == MessageKind.VoidRequest)
            .ToImmutableArray();
        EquatableArray<MessageModel> notifications = messages
            .Where(static message => message.Kind == MessageKind.Notification)
            .ToImmutableArray();

        bool useDictionaries = messages.Count > DictionaryThreshold;
        bool needsBoxAsync = responseMessages.Any(static message => message.ResponseIsValueType);
        bool needsToObjectTaskAsync = !useDictionaries && voidMessages.Count > 0;

        var builder = new StringBuilder();
        builder.Append(GeneratedFileHeader);
        builder.Append("namespace ").Append(KnownMetadataNames.GeneratedNamespace).Append('\n');
        builder.Append("{\n");

        AppendLine(builder, 1, "internal sealed class Mediator : global::RA.Utilities.Feature.Abstractions.IMediator");
        AppendLine(builder, 1, "{");
        AppendLine(builder, 2, "private readonly global::System.IServiceProvider _provider;");
        AppendLine(builder, 2, "private readonly global::Microsoft.Extensions.Logging.ILogger<Mediator> _logger;");
        AppendConstructor(builder);

        foreach (MessageModel message in responseMessages)
        {
            string handler = GetHandlerFullyQualifiedName(allHandlers, message);
            AppendResponseSend(builder, message, handler);
            AppendResponseContextSend(builder, message, handler);
        }

        foreach (MessageModel message in voidMessages)
        {
            string handler = GetHandlerFullyQualifiedName(allHandlers, message);
            AppendVoidSend(builder, message, handler);
            AppendVoidContextSend(builder, message, handler);
        }

        foreach (MessageModel message in notifications)
        {
            AppendPublish(builder, message);
            AppendContextPublish(builder, message);
        }

        AppendObjectSend(builder, responseMessages, voidMessages, useDictionaries);
        AppendObjectPublish(builder, notifications, useDictionaries);

        AppendVoidInterfaceSend(builder);
        AppendResponseInterfaceSend(builder);
        AppendVoidContextInterfaceSend(builder);
        AppendResponseContextInterfaceSend(builder);
        AppendPublishInterface(builder);
        AppendContextPublishInterface(builder);

        if (useDictionaries)
        {
            AppendObjectSendDictionary(builder, responseMessages, voidMessages);
            AppendPublishDictionary(builder, notifications);
        }

        AppendHelpers(builder, needsBoxAsync, needsToObjectTaskAsync);

        AppendLine(builder, 1, "}");
        builder.Append('\n');

        if (!initializerDisabled)
        {
            AppendInitializer(builder);
        }

        builder.Append("}\n");
        return builder.ToString();
    }

    private static void AppendConstructor(StringBuilder builder)
    {
        AppendLine(builder, 2, "public Mediator(global::System.IServiceProvider provider, global::Microsoft.Extensions.Logging.ILogger<Mediator> logger)");
        AppendLine(builder, 2, "{");
        AppendLine(builder, 3, "if (provider is null) { throw new global::System.ArgumentNullException(nameof(provider)); }");
        AppendLine(builder, 3, "if (logger is null) { throw new global::System.ArgumentNullException(nameof(logger)); }");
        AppendLine(builder, 3, "_provider = provider;");
        AppendLine(builder, 3, "_logger = logger;");
        AppendLine(builder, 2, "}");
    }

