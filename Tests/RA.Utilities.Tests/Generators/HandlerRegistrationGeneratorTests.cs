    [Fact]
    public void CompileAndLoad_ModuleInitializer_QueuesRegistrations()
    {
        Assembly assembly = GeneratorTestHost.CompileAndLoad(GeneratorTestHost.RuntimeSources, HandlerSources);

        // Assembly.Load runs the generated module initializer, which queues registrations into the
        // in-memory copy of HandlerRegistrations; applying them to a real ServiceCollection must
        // register the discovered handlers.
        Type handlerRegistrationsType = assembly.GetType("RA.Utilities.Feature.Generated.HandlerRegistrations")
            ?? throw new InvalidOperationException("HandlerRegistrations type not found in the emitted assembly.");
        MethodInfo applyAll = handlerRegistrationsType.GetMethod("ApplyAll", BindingFlags.Public | BindingFlags.Static)
            ?? throw new InvalidOperationException("ApplyAll method not found.");

        var services = new ServiceCollection();
        applyAll.Invoke(null, [services]);

        Type pingType = assembly.GetType("Sample.Ping")
            ?? throw new InvalidOperationException("Sample.Ping type not found in the emitted assembly.");
        Type pongType = assembly.GetType("Sample.Pong")
            ?? throw new InvalidOperationException("Sample.Pong type not found in the emitted assembly.");
        Type handlerInterfaceDefinition = assembly.GetType("RA.Utilities.Feature.Abstractions.IRequestHandler`2")
            ?? throw new InvalidOperationException("IRequestHandler<,> not found in the emitted assembly.");
        Type responseHandlerInterface = handlerInterfaceDefinition.MakeGenericType(pingType, pongType);

        using ServiceProvider provider = services.BuildServiceProvider();
        object? handler = provider.GetService(responseHandlerInterface);

        handler.Should().NotBeNull();
        handler.GetType().FullName.Should().Be("Sample.PingHandler");
    }
