    private const string HandlerSources = """
        namespace Sample
        {
            public record Ping(string Value) : global::RA.Utilities.Feature.Abstractions.IRequest<Pong>;

            public record Pong(string Value);

            public class PingHandler : global::RA.Utilities.Feature.Abstractions.IRequestHandler<Ping, Pong>
            {
                public System.Threading.Tasks.Task<Pong> HandleAsync(Ping request, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.FromResult(new Pong(request.Value));
            }

            public record DoNothing : global::RA.Utilities.Feature.Abstractions.IRequest;

            public class DoNothingHandler : global::RA.Utilities.Feature.Abstractions.IRequestHandler<DoNothing>
            {
                public System.Threading.Tasks.Task HandleAsync(DoNothing request, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.CompletedTask;
            }

            public record OrderPlaced : global::RA.Utilities.Feature.Abstractions.INotification;

            public class EmailNotifier : global::RA.Utilities.Feature.Abstractions.INotificationHandler<OrderPlaced>
            {
                public System.Threading.Tasks.Task HandleAsync(OrderPlaced notification, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.CompletedTask;
            }
        }
        """;

    private const string AbstractBaseSources = """
        namespace Sample
        {
            public record SpecialPing(string Value) : global::RA.Utilities.Feature.Abstractions.IRequest<Pong>;

            public record Pong(string Value);

            public abstract class AbstractPingHandler : global::RA.Utilities.Feature.Abstractions.IRequestHandler<SpecialPing, Pong>
            {
                public abstract System.Threading.Tasks.Task<Pong> HandleAsync(SpecialPing request, System.Threading.CancellationToken cancellationToken);
            }

            public class SpecialPingHandler : AbstractPingHandler
            {
                public override System.Threading.Tasks.Task<Pong> HandleAsync(SpecialPing request, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.FromResult(new Pong(request.Value));
            }
        }
        """;

    private const string ExpectedGeneratedSource = """"
        // <auto-generated/>
        #pragma warning disable
        #nullable enable

        namespace RA.Utilities.Feature.Generated
        {
            internal static class HandlerRegistrationInitializer
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Initialize()
                {
                    global::RA.Utilities.Feature.Generated.HandlerRegistrations.Add(static services =>
                    {
                        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddTransient<global::RA.Utilities.Feature.Abstractions.INotificationHandler<global::Sample.OrderPlaced>, global::Sample.EmailNotifier>(services);
                        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<global::RA.Utilities.Feature.Abstractions.IRequestHandler<global::Sample.DoNothing>, global::Sample.DoNothingHandler>(services);
                        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<global::RA.Utilities.Feature.Abstractions.IRequestHandler<global::Sample.Ping, global::Sample.Pong>, global::Sample.PingHandler>(services);
                    });
                }
            }
        }
        """";

    [Fact]
    public void GeneratesModuleInitializer_ForAllHandlerKinds()
    {
        (Compilation _, GeneratorDriverRunResult runResult) =
            GeneratorTestHost.RunGenerator(GeneratorTestHost.RuntimeSources, HandlerSources);

        runResult.Diagnostics.Should().BeEmpty();
        GeneratedSourceResult generatedSource = runResult.Results.Single().GeneratedSources.Should().ContainSingle().Subject;
        generatedSource.HintName.Should().Be("RA.Utilities.Feature.HandlerRegistrations.g.cs");
        generatedSource.SourceText.ToString().Should().Be(ExpectedGeneratedSource.Replace("\r\n", "\n") + "\n");
    }

    [Fact]
    public void ConcreteHandler_DerivingFromAbstractBase_IsRegisteredAsItself()
    {
        (Compilation _, GeneratorDriverRunResult runResult) =
            GeneratorTestHost.RunGenerator(GeneratorTestHost.RuntimeSources, AbstractBaseSources);

        runResult.Diagnostics.Should().BeEmpty();
        string generated = runResult.Results.Single().GeneratedSources.Single().SourceText.ToString();

        generated.Should().Contain("IRequestHandler<global::Sample.SpecialPing, global::Sample.Pong>, global::Sample.SpecialPingHandler>");
        generated.Should().NotContain("AbstractPingHandler");
    }

